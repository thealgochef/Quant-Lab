"""Trade-path evidence, bundles, and capabilities (CS §5.1) — fidelity FIRST.

Historically truthful path evidence for `ifvg_prop_robust_config_search_v1`
R3: a 1-minute bar does not record its intrabar order
(``observed_intrabar_order`` can only be ``"unknown"``); assumed intrabar
paths are SCENARIOS generated by a registered policy (two policies = two
scenario identities and, on order-sensitive trades, two different results);
only actual ordered market/fill evidence supports chronology-sensitive
historical claims. Rule support is CAPABILITY-based — never inferred from an
ordinal fidelity enum — and fails closed with a
:class:`PathCapabilityReport`.

Additive module: the existing evaluation-only propsim API is untouched.
"""

